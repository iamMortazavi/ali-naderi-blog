    /** All site CSS in one small block, inlined in <head> so the first paint needs no extra request. */
    public static function inlineCss(): string
    {
        $version = collect(self::CSS)->map(fn ($f) => filemtime(public_path("site/css/{$f}")))->implode('-');

        return Cache::rememberForever("site-css:{$version}", function () {
            $css = collect(self::CSS)->map(fn ($f) => file_get_contents(public_path("site/css/{$f}")))->implode("\n");
            $css = preg_replace('#/\*.*?\*/#s', '', $css);
            $css = preg_replace('/\s+/', ' ', $css);

            return trim(preg_replace('/\s*([{};:,>])\s*/', '$1', $css));
        });
    }

    /** URL of a file in public/site with its modification time, so browsers fetch new versions. */
    public static function url(string $file): string
    {
        return '/site/'.$file.'?v='.filemtime(public_path('site/'.$file));
    }

